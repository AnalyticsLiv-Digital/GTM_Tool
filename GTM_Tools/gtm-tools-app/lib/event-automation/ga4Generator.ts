import type {
  EventSchemaRow,
  GeneratedGA4Tag,
  GeneratedGA4Trigger,
  GeneratedGA4Variable,
  GA4MeasurementIdConfig,
  SelectorType,
} from "./types";

// =====================================================
// HELPERS
// =====================================================

function cleanName(value: string): string {
  return value
    .trim()
    .replace(/\s+/g, " ");
}

// =====================================================
// TRIGGER TYPES
// =====================================================
//
// IMPORTANT
//
// Do NOT assume every event uses the same click trigger.
//
// The website inspection provides:
//
// - tagName
// - id
// - classes
// - href
// - type
// - selector
// - selectorType
// - closestTag
// - interactionExpression
//
// We use those values to select the most suitable GTM
// trigger configuration.
//
// =====================================================

type GTMClickTriggerType =
  | "CLICK"
  | "LINK_CLICK"
  | "FORM_SUBMISSION"
  | "ELEMENT_VISIBILITY"
  | "CUSTOM_EVENT";

// =====================================================
// INSPECTED EVENT SHAPE
// =====================================================
//
// EventSchemaRow is intentionally extended here instead
// of changing the Excel schema.
//
// =====================================================

type ResolvedEvent = EventSchemaRow & {
  id?: string;
  classes?: string[];
  href?: string;
  type?: string;
  ariaLabel?: string;
  alt?: string;
  interactionExpression?: string;
  querySelectorExpression?: string;
  closestTag?: string;
  selectorSource?: string;
  detectedTriggerType?: GTMClickTriggerType;
  triggerType?: string;
};

// =====================================================
// SELECTOR VARIABLE
// =====================================================
//
// GTM built-in variables:
//
// ID    -> {{Click ID}}
// CLASS -> {{Click Classes}}
//
// IMPORTANT
//
// The actual selector is still generated by website
// inspection.
//
// We only decide which GTM built-in variable should
// evaluate it.
//
// =====================================================

function getSelectorVariable(
  event: ResolvedEvent
): {
  variableName: string;
  variableType: "id" | "class";
} | null {
  if (!event.selectorType) {
    return null;
  }

  if (event.selectorType === "id") {
    return {
      variableName: "{{Click ID}}",
      variableType: "id",
    };
  }

  if (event.selectorType === "class") {
    return {
      variableName: "{{Click Classes}}",
      variableType: "class",
    };
  }

  return null;
}

// =====================================================
// DETECT SELECTOR TYPE
// =====================================================
//
// If inspection already decided the selector type,
// trust that.
//
// Otherwise inspect the selector itself.
//
// =====================================================

function detectSelectorType(
  event: ResolvedEvent
): SelectorType | undefined {
  if (
    event.selectorType === "id" ||
    event.selectorType === "class"
  ) {
    return event.selectorType;
  }

  const selector =
    event.selector?.trim() ?? "";

  if (!selector) {
    return undefined;
  }

  // Example:
  //
  // #contact-button
  //
  if (selector.startsWith("#")) {
    return "id";
  }

  // Example:
  //
  // .contact-button
  //
  if (selector.startsWith(".")) {
    return "class";
  }

  return "auto";
}

// =====================================================
// DETECT ELEMENT TYPE
// =====================================================
//
// This is the important part.
//
// We do NOT assume:
//
// Click - Just Links
//
// for every event.
//
// =====================================================

function detectTriggerType(
  event: ResolvedEvent
): GTMClickTriggerType {
  // ---------------------------------------------------
  // If inspection already determined the trigger type
  // ---------------------------------------------------

  if (
    event.detectedTriggerType
  ) {
    return event.detectedTriggerType;
  }

  if (
    event.triggerType ===
    "FORM_SUBMISSION"
  ) {
    return "FORM_SUBMISSION";
  }

  if (
    event.triggerType ===
    "ELEMENT_VISIBILITY"
  ) {
    return "ELEMENT_VISIBILITY";
  }

  if (
    event.triggerType ===
    "LINK_CLICK"
  ) {
    return "LINK_CLICK";
  }

  // ---------------------------------------------------
  // FORM
  // ---------------------------------------------------

  const tagName =
    event.tagName
      ?.trim()
      .toLowerCase() ?? "";

  const type =
    event.type
      ?.trim()
      .toLowerCase() ?? "";

  if (
    tagName === "form"
  ) {
    return "FORM_SUBMISSION";
  }

  // ---------------------------------------------------
  // LINK
  // ---------------------------------------------------

  if (
    tagName === "a" ||
    event.closestTag
      ?.trim()
      .toLowerCase() === "a"
  ) {
    return "LINK_CLICK";
  }

  // ---------------------------------------------------
  // DEFAULT CLICK
  // ---------------------------------------------------
  //
  // button
  // div
  // span
  // img
  // svg
  // input
  // etc.
  //
  // These should use GTM All Elements / click logic.
  //

  if (
    tagName === "button" ||
    tagName === "div" ||
    tagName === "span" ||
    tagName === "img" ||
    tagName === "svg" ||
    tagName === "input" ||
    type === "button" ||
    type === "submit"
  ) {
    return "CLICK";
  }

  // ---------------------------------------------------
  // DEFAULT
  // ---------------------------------------------------

  return "CLICK";
}

// =====================================================
// TRIGGER DISPLAY NAME
// =====================================================

function getTriggerTypeName(
  triggerType: GTMClickTriggerType
): string {
  switch (triggerType) {
    case "LINK_CLICK":
      return "Just Links";

    case "CLICK":
      return "All Elements";

    case "FORM_SUBMISSION":
      return "Form Submission";

    case "ELEMENT_VISIBILITY":
      return "Element Visibility";

    case "CUSTOM_EVENT":
      return "Custom Event";

    default:
      return "All Elements";
  }
}

// =====================================================
// MATCH TYPE
// =====================================================

function getMatchType(
  event: ResolvedEvent
): NonNullable<EventSchemaRow["matchType"]> {
  if (event.matchType) {
    return event.matchType;
  }

  if (
    event.selectorType === "id"
  ) {
    return "equals";
  }

  if (
    event.selectorType === "class"
  ) {
    return "contains";
  }

  return "contains";
}

// =====================================================
// MATCH VALUE
// =====================================================

function getMatchValue(
  event: ResolvedEvent
): string {
  if (
    event.matchValue?.trim()
  ) {
    return event.matchValue.trim();
  }

  // ---------------------------------------------------
  // ID
  // ---------------------------------------------------

  if (
    event.selectorType === "id"
  ) {
    const selector =
      event.selector?.trim() ?? "";

    return selector.startsWith("#")
      ? selector.substring(1)
      : selector;
  }

  // ---------------------------------------------------
  // CLASS
  // ---------------------------------------------------

  if (
    event.selectorType === "class"
  ) {
    const selector =
      event.selector?.trim() ?? "";

    return selector.startsWith(".")
      ? selector.substring(1)
      : selector;
  }

  // ---------------------------------------------------
  // FALLBACK
  // ---------------------------------------------------

  return (
    event.selector?.trim() ||
    event.eventName
  );
}

// =====================================================
// VARIABLE
// =====================================================
//
// The variable is based on the selector discovered
// from the website.
//
// =====================================================

function generateVariable(
  event: ResolvedEvent
): GeneratedGA4Variable {
  const selectorType =
    detectSelectorType(event);

  const normalizedEventName =
    cleanName(event.eventName);

  const variableName =
    `GA4 - ${normalizedEventName} - Selector`;

  const selectorInfo =
    getSelectorVariable({
      ...event,
      selectorType,
    });

  // ---------------------------------------------------
  // No selector
  // ---------------------------------------------------

  if (!selectorInfo) {
    return {
      name: variableName,

      type: "v",

      value:
        `{{${event.eventName}}}`,

      parameter: [
        {
          key: "name",
          type: "TEMPLATE",
          value:
            event.eventName,
        },
      ],

      sourceEvent:
        event.eventName,

      selector:
        event.selector,

      selectorType,

      dataLayerPath:
        event.eventName,
    };
  }

  // ---------------------------------------------------
  // ID / CLASS
  // ---------------------------------------------------

  return {
    name: variableName,

    type: "v",

    value:
      selectorInfo.variableName,

    parameter: [
      {
        key: "name",
        type: "TEMPLATE",
        value:
          selectorInfo.variableName,
      },

      {
        key: "selectorType",
        type: "TEMPLATE",
        value:
          selectorType ?? "auto",
      },

      {
        key: "selector",
        type: "TEMPLATE",
        value:
          event.selector ?? "",
      },
    ],

    sourceEvent:
      event.eventName,

    selector:
      event.selector,

    selectorType,

    dataLayerPath:
      event.eventName,
  };
}

// =====================================================
// TRIGGER
// =====================================================

function generateTrigger(
  event: ResolvedEvent
): GeneratedGA4Trigger {
  const selectorType =
    detectSelectorType(event);

  const resolvedEvent = {
    ...event,
    selectorType,
  };

  const triggerType =
    detectTriggerType(
      resolvedEvent
    );

  const triggerTypeName =
    getTriggerTypeName(
      triggerType
    );

  const selectorInfo =
    getSelectorVariable(
      resolvedEvent
    );

  const matchType =
    getMatchType(
      resolvedEvent
    );

  const matchValue =
    getMatchValue(
      resolvedEvent
    );

  const triggerName =
    `GA4 - ${cleanName(
      event.eventName
    )} - ${triggerTypeName}`;

  // ===================================================
  // BASE PARAMETERS
  // ===================================================

  const parameters: {
    key: string;
    type: string;
    value: string;
  }[] = [
      {
        key: "triggerType",
        type: "TEMPLATE",
        value: triggerType,
      },

      {
        key: "eventName",
        type: "TEMPLATE",
        value: event.eventName,
      },
    ];

  // ===================================================
  // SELECTOR PARAMETERS
  // ===================================================

  if (
    selectorInfo &&
    event.selector
  ) {
    parameters.push(
      {
        key: "variableName",
        type: "TEMPLATE",
        value:
          selectorInfo.variableName,
      },
      {
        key: "matchType",
        type: "TEMPLATE",
        value: matchType,
      },
      {
        key: "matchValue",
        type: "TEMPLATE",
        value: matchValue,
      }
    );
  }

  // ===================================================
  // LINK INFORMATION
  // ===================================================

  if (
    triggerType ===
    "LINK_CLICK"
  ) {
    parameters.push({
      key: "linkClick",
      type: "BOOLEAN",
      value: "true",
    });
  }

  // ===================================================
  // FORM INFORMATION
  // ===================================================

  if (
    triggerType ===
    "FORM_SUBMISSION"
  ) {
    parameters.push({
      key: "formSubmission",
      type: "BOOLEAN",
      value: "true",
    });
  }

  // ===================================================
  // INTERACTION EXPRESSION
  // ===================================================

  if (
    event.interactionExpression
  ) {
    parameters.push({
      key: "interactionExpression",
      type: "TEMPLATE",
      value:
        event.interactionExpression,
    });
  }

  // ===================================================
  // QUERY SELECTOR EXPRESSION
  // ===================================================

  if (
    event.querySelectorExpression
  ) {
    parameters.push({
      key:
        "querySelectorExpression",

      type:
        "TEMPLATE",

      value:
        event.querySelectorExpression,
    });
  }

  return {
    name: triggerName,

    type: triggerType,

    customEventName:
      event.eventName,

    parameter: parameters,

    sourceEvent:
      event.eventName,

    selector:
      event.selector,

    selectorType,

    variableName:
      selectorInfo?.variableName,

    matchType,

    matchValue,
  };
}

// =====================================================
// TAG
// =====================================================

function generateTag(
  event: ResolvedEvent,
  measurementId: string,
  triggerName: string
): GeneratedGA4Tag {
  return {
    name:
      `GA4 - ${cleanName(
        event.eventName
      )} - Event`,

    type:
      "gaawe",

    parameter: [
      {
        key:
          "eventName",

        type:
          "TEMPLATE",

        value:
          event.eventName,
      },

      {
        key:
          "measurementIdOverride",

        type:
          "TEMPLATE",

        value:
          measurementId,
      },
    ],

    firingTriggerName:
      triggerName,

    sourceEvent:
      event.eventName,

    measurementId,

    selector:
      event.selector,

    selectorType:
      event.selectorType,
  };
}

// =====================================================
// NORMALIZE EVENT
// =====================================================

function normalizeEvent(
  event: EventSchemaRow
): ResolvedEvent {
  const resolved =
    event as ResolvedEvent;

  const selectorType =
    detectSelectorType(
      resolved
    );

  return {
    ...resolved,

    selectorType,
  };
}

// =====================================================
// GENERATE AUTOMATION
// =====================================================

export function generateGA4Automation(
  events: EventSchemaRow[],
  measurementConfig:
    GA4MeasurementIdConfig
) {
  const variables:
    GeneratedGA4Variable[] = [];

  const triggers:
    GeneratedGA4Trigger[] = [];

  const tags:
    GeneratedGA4Tag[] = [];

  // ===================================================
  // MEASUREMENT ID
  // ===================================================

  const measurementId =
    typeof measurementConfig ===
      "string"
      ? (
        measurementConfig as string
      ).trim()
      : (
        measurementConfig as {
          value?: string;
        }
      )?.value?.trim() ||
      "{{GA4 Measurement ID}}";

  // ===================================================
  // VALIDATE
  // ===================================================

  if (!measurementId) {
    throw new Error(
      "GA4 Measurement ID is required."
    );
  }

  // ===================================================
  // EVENTS
  // ===================================================

  for (
    const rawEvent of events
  ) {
    const event =
      normalizeEvent(
        rawEvent
      );

    // -------------------------------------------------
    // VARIABLE
    // -------------------------------------------------

    variables.push(
      generateVariable(
        event
      )
    );

    // -------------------------------------------------
    // TRIGGER
    // -------------------------------------------------

    const trigger =
      generateTrigger(
        event
      );

    triggers.push(
      trigger
    );

    // -------------------------------------------------
    // TAG
    // -------------------------------------------------

    tags.push(
      generateTag(
        event,
        measurementId,
        trigger.name
      )
    );
  }

  // ===================================================
  // RETURN
  // ===================================================

  return {
    variables,

    triggers,

    tags,
  };
}