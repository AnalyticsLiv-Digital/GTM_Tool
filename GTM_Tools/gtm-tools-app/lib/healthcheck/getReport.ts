type GtmRecord = Record<string, unknown>;
type ImportedGtmData = {
  tags: GtmRecord[];
  triggers: GtmRecord[];
  variables: GtmRecord[];
};

function isRecordArray(value: unknown): value is GtmRecord[] {
  return (
    Array.isArray(value) &&
    value.every((item) => typeof item === "object" && item !== null && !Array.isArray(item))
  );
}

function affectedItem(x: unknown): { name: string; id?: string; editUrl?: string } {
  if (typeof x === "string") return { name: x };
  if (x && typeof x === "object") {
    const o = x as { name?: unknown; id?: unknown; editUrl?: unknown };
    const name = typeof o.name === "string" ? o.name : typeof o.id === "string" ? o.id : "";
    if (name) {
      return {
        name,
        id: typeof o.id === "string" ? o.id : undefined,
        editUrl: typeof o.editUrl === "string" ? o.editUrl : undefined,
      };
    }
  }
  try {
    return { name: JSON.stringify(x) };
  } catch {
    return { name: "Unknown item" };
  }
}

// Free, no-AI report built from the rule engine results.
function buildLocalAudit(report: { results: any[]; score: number }) {
  const failed = report.results.filter((r) => !r.passed);
  const passed = report.results.filter((r) => r.passed);
  const list = (sev: string[]) =>
    failed
      .filter((r) => sev.includes(r.severity))
      .map((r) => `- **${r.title}**: ${r.recommendation || r.description}`)
      .join("\n") || "- None found";

  return `## Critical Issues
${list(["HIGH"])}

## Warnings / Cleanup Opportunities
${list(["MEDIUM", "LOW"])}

## What's Working Well
${passed.slice(0, 8).map((r) => `- ${r.title}`).join("\n") || "- Nothing passed yet"}

## What To Do Next
- Fix the critical issues first, then clean up the warnings.
- Re-run the health check and validate in Preview Mode before publishing.

_Score: ${report.score}%. Generated by the built-in rule engine._`;
}

export async function POST(req: NextRequest) {
  let userApiKey: string | null = null;

  try {
    userApiKey = readAnthropicKey(req);

    // Only logged-in users can use the chat.
    const accessToken = await getValidGoogleAccessToken();
    if (!accessToken) {
      return NextResponse.json(
        { success: false, code: "unauthorized", error: "Please sign in with Google to run the AI audit." },
        { status: 401 }
      );
    }

    // 2) Rate limit: 5 AI audits per hour per user/IP.
    const windowMs = 60 * 60 * 1000;
    if (!rateLimit(`ai-audit:${clientIp(req)}`, 5, windowMs)) {
      return NextResponse.json(
        {
          success: false,
          error: "Chat limit reached. Try again in an hour.",
        },
        { status: 429, headers: { "Retry-After": "3600" } }
      );
    }

    const body = await req.json();
    const { healthReport, messages } = body;
    // Accept both field names the page may send.
    const claudeText: string = body.claudeText ?? body.claudeReport?.resultText ?? "";

    if (!Array.isArray(messages) || messages.length === 0) {
      return NextResponse.json({ success: false, error: "No messages." }, { status: 400 });
    }

    const failed = (healthReport?.results ?? []).filter((r: any) => !r.passed);
    const prompt = [
      "Review the GTM health check and respond to the user's latest message.",
      healthReport ? `Health check report:\n${JSON.stringify(healthReport)}` : "",
      claudeText ? `Existing audit report:\n${claudeText}` : "",
      `Conversation:\n${messages.map((message: any) => `${message.role}: ${message.content}`).join("\n")}`,
    ]
      .filter(Boolean)
      .join("\n\n");

    const { client, model } = await getClaude({ userApiKey: userApiKey ?? undefined });
    const response = await client.messages.create({
      model: "claude-haiku-5-5", // switch to "claude-sonnet-5-5" for deeper audits
      max_tokens: 8000,
      system: "You are a senior Google Tag Manager implementation and analytics consultant.",
      messages: [{ role: "user", content: prompt }],
    });

    const resultText = response.content
      .filter((content: any) => content.type === "text")
      .map((content: any) => content.text)
      .join("\n\n")
      .trim();

    return NextResponse.json({ success: true, reply: resultText });
  } catch (error) {
    if (error instanceof ClaudeNotConfiguredError) {
      console.error("[claude] Not configured:", String(error));
      return NextResponse.json({ success: false, error: "AI chat is not configured." }, { status: 500 });
    }
    const failure = classifyAnthropicError(error);
    const response = NextResponse.json(
      { success: false, code: failure.code, error: failure.message },
      { status: failure.status }
    );
    if (userApiKey && failure.code === "invalid_key") clearAnthropicKeyCookie(response);
    return response;
  }
}